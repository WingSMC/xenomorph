// ── Generator listener ──────────────────────────────────────────────

struct TsGenerator {
    source: String,
    workdir: PathBuf,
    out: String,
    abs_path: PathBuf,
    module_path: String,
    /// Output directory override from `[plugins.typescript].output`.
    /// If None, writes .ts files next to the .xen source files.
    output_dir: Option<PathBuf>,
    /// Imported types keyed by module path, for generating destructured imports.
    imported_types: HashMap<String, Vec<String>>,
    import_selections: HashMap<String, Vec<String>>,
    /// Complete semantic graph used to distinguish generated declarations
    /// from static types that require an explicit TypeScript mapping.
    type_hierarchy: TypeHierarchy,
    /// Nesting depth while walking annotation arguments, which are metadata
    /// rather than emitted TypeScript value types.
    annotation_depth: usize,
}

impl TsGenerator {
    fn new() -> Self {
        Self {
            source: String::new(),
            workdir: PathBuf::new(),
            out: String::new(),
            abs_path: PathBuf::new(),
            module_path: String::new(),
            output_dir: None,
            imported_types: HashMap::new(),
            import_selections: HashMap::new(),
            type_hierarchy: TypeHierarchy::default(),
            annotation_depth: 0,
        }
    }
}

impl<'src> AnalyzerListener<'src> for TsGenerator {
    fn set_source(&mut self, source: &str) {
        self.source.clear();
        self.source.push_str(source);
    }
    fn on_before_module(&mut self, scope: &ScopeInfo) {
        self.abs_path = scope.abs_path.clone();
        self.module_path = scope.module_path.clone();
        self.imported_types = scope.imported_types.clone();
        self.import_selections = scope.import_selections.clone();
        self.type_hierarchy = scope.type_hierarchy.clone();
        self.annotation_depth = 0;
        self.out.clear();
        self.out
            .push_str("// Auto-generated by xenomorph-typescript — do not edit.\n\n");

        let mut imports: Vec<_> = scope.imported_types.iter().collect();
        imports.sort_by_key(|(left, _)| *left);

        for (import_path, names) in imports {
            if !names.is_empty() {
                let destructured = names.join(", ");
                let ts_import_path = ts_import_specifier(&scope.module_path, import_path);
                self.out.push_str(&format!(
                    "import type {{ {destructured} }} from \"{ts_import_path}\";\n"
                ));
            }
        }
    }

    fn on_before_ast(
        &mut self,
        ast: &[Declaration],
        _errors: &mut Vec<xenomorph_common::XenoDiagnostic>,
    ) {
        // Generate type declarations
        for decl in ast {
            if let Declaration::Import {
                public: Some(_),
                path,
                names,
                ..
            } = decl
            {
                let mut exports: std::collections::BTreeMap<String, Vec<&str>> =
                    std::collections::BTreeMap::new();
                let selected: Vec<_> = names
                    .iter()
                    .flat_map(|name| {
                        if name.text(&self.source) == "*" {
                            self.import_selections
                                .get(&path.join("/"))
                                .into_iter()
                                .flatten()
                                .map(String::as_str)
                                .collect()
                        } else {
                            vec![name.text(&self.source)]
                        }
                    })
                    .collect();
                for text in selected {
                    if let Some(path) = self
                        .type_hierarchy
                        .get_type(text)
                        .and_then(|d| d.module_path.clone())
                    {
                        exports.entry(path).or_default().push(text);
                    }
                }
                for (path, names) in exports {
                    self.out.push_str(&format!(
                        "export type {{ {} }} from \"{}\";\n",
                        names.join(", "),
                        ts_import_specifier(&self.module_path, &path)
                    ));
                }
            }
            if let Declaration::Type {
                docs,
                name,
                generics,
                ty: t,
                public,
                ..
            } = decl
            {
                generate_type_decl(
                    &mut self.out,
                    docs,
                    name.text(&self.source),
                    generics.as_deref(),
                    t,
                    &self.source,
                    public.is_some(),
                );
            }
        }
    }

    fn on_before_decl(&mut self, decl: &Declaration, errors: &mut Vec<XenoDiagnostic>) {
        if let Declaration::Type { name, generics, .. } = decl {
            report_typescript_keyword(name, "type", errors, &self.source);
            for (generic, _) in generics.as_deref().unwrap_or_default() {
                report_typescript_keyword(generic, "generic parameter", errors, &self.source);
            }
        }
    }

    fn on_simple_type(&mut self, ty: &SimpleType, errors: &mut Vec<XenoDiagnostic>) {
        if self.annotation_depth == 0 {
            if let Some(diagnostic) = unsupported_target_type_diagnostic(
                "TypeScript",
                ty,
                &self.type_hierarchy,
                &self.source,
                has_native_typescript_mapping,
            ) {
                errors.push(diagnostic);
            }
        }

        let literal = match ty.inner() {
            SimpleType::Literal(literal) => literal,
            _ => return,
        };
        if let Literal::Float(float) = literal {
            if !xenomorph_common::parser::decimal_roundtrips_as(&float.value, FloatSize::F64) {
                errors.push(XenoDiagnostic {
                    tags: vec![],
                    location: float.cast.unwrap_or(float.token),
                    message: format!(
                        "TypeScript cannot represent floating-point literal '{}' exactly with its built-in number type.",
                        float.token.text(&self.source)
                    ),
                    severity: XenoDiagSeverity::Err,
                });
            }
        }
    }

    fn on_before_annotation(
        &mut self,
        _name: &TokenData,
        _args: &[Expr],
        _errors: &mut Vec<XenoDiagnostic>,
    ) {
        self.annotation_depth += 1;
    }

    fn on_after_annotation(
        &mut self,
        _name: &TokenData,
        _args: &[Expr],
        _errors: &mut Vec<XenoDiagnostic>,
    ) {
        self.annotation_depth = self.annotation_depth.saturating_sub(1);
    }

    fn on_after_module(&mut self, scope: &ScopeInfo) {
        let out_path = match &self.output_dir {
            Some(dir) => {
                let filename = format!(
                    "{}.ts",
                    scope
                        .module_path
                        .replace('/', std::path::MAIN_SEPARATOR_STR)
                );
                let path = self.workdir.join(dir).join(filename);
                if let Some(parent) = path.parent() {
                    let _ = fs::create_dir_all(parent);
                }
                path
            }
            None => self.abs_path.with_extension("ts"),
        };
        match fs::write(&out_path, &self.out) {
            Ok(_) => println!("✓ {} → {}", scope.module_path, out_path.display()),
            Err(e) => eprintln!("✗ {} — failed to write: {}", scope.module_path, e),
        }
    }
}

// ── Type declaration generation ─────────────────────────────────────

fn generate_type_decl(
    out: &mut String,
    docs: &Option<String>,
    name: &str,
    generics: Option<&[(TokenData, Option<TokenData>)]>,
    t: &XenoType,
    source: &str,
    public: bool,
) {
    let export = if public { "export " } else { "" };
    let annotations: Vec<String> =
        t.1.iter()
            .map(|value| format_annotation(value, source))
            .collect();
    let deprecated =
        t.1.iter()
            .find(|annotation| annotation.ident.text(source) == "deprecated");
    let generic_params = format_generic_params(generics, source);

    // JSDoc
    if docs.is_some() || !annotations.is_empty() {
        out.push_str("/**\n");
        if let Some(doc) = docs {
            for line in doc.lines() {
                out.push_str(&format!(" * {line}\n"));
            }
        }
        for ann in &annotations {
            for line in ann.lines() {
                out.push_str(&format!(" * {line}\n"));
            }
        }
        out.push_str(" */\n");
    }

    if let Type::Struct(fields) = &t.0 {
        generate_interface(out, name, &generic_params, fields, source, export);
        return;
    }

    if let Type::Enum(variants) = &t.0 {
        generate_enum(out, name, variants, source, export);
        return;
    }

    if let Type::Set(set) = &t.0 {
        if let Some(values) = &set.values {
            let elems = values
                .iter()
                .map(|value| literal_to_ts(value, source))
                .collect::<Vec<_>>();
            let constraint = set
                .element_type
                .as_ref()
                .map_or_else(String::new, |element| {
                    format!(
                        " satisfies readonly {}[]",
                        simple_type_to_ts(element, source)
                    )
                });
            out.push_str(&format!(
                "{export}const {name}_TYPE_VALUES = [{}] as const{constraint};\n",
                elems.join(", ")
            ));
            if let Some(deprecated) = deprecated {
                push_jsdoc(out, &format_annotation(deprecated, source), "");
            }
            out.push_str(&format!(
                "{export}type {name} = (typeof {name}_TYPE_VALUES)[number];\n\n"
            ));
            return;
        }
    }

    if let Type::Tuple(items) = &t.0 {
        if is_all_required_literals(items) {
            let values = items
                .iter()
                .map(|value| simple_type_to_ts(value, source))
                .collect::<Vec<_>>();
            out.push_str(&format!(
                "{export}const {name}_TYPE_VALUES = [{}] as const;\n",
                values.join(", ")
            ));
            if let Some(deprecated) = deprecated {
                push_jsdoc(out, &format_annotation(deprecated, source), "");
            }
            out.push_str(&format!(
                "{export}type {name} = typeof {name}_TYPE_VALUES;\n\n"
            ));
            return;
        }
    }

    let ts = type_to_ts(&t.0, source);
    out.push_str(&format!("{export}type {name}{generic_params} = {ts};\n\n"));
}

// ── Interface (struct) generation ───────────────────────────────────

fn generate_interface(
    out: &mut String,
    name: &str,
    generic_params: &str,
    fields: &[KeyValExpr],
    source: &str,
    export: &str,
) {
    out.push_str(&format!("{export}interface {name}{generic_params} {{\n"));
    for (key, value, docs) in fields {
        let ts_type = simple_type_to_ts(value, source);
        let optional = is_optional(value);

        if let Some(docs) = docs {
            push_jsdoc(out, &extract_documentation(docs, source), "  ");
        }
        let opt = if optional { "?" } else { "" };
        out.push_str(&format!(
            "  {}{opt}: {ts_type};\n",
            typescript_property_name(key.text(source))
        ));
    }
    out.push_str("}\n\n");
}

// ── Enum generation ─────────────────────────────────────────────────

fn generate_enum(
    out: &mut String,
    name: &str,
    variants: &[KeyValExpr],
    source: &str,
    export: &str,
) {
    let all_numeric = variants.iter().all(|(_, value, _)| match value {
        SimpleType::Literal(Literal::Float(_)) => true,
        SimpleType::Literal(Literal::Int(integer)) => !integer_uses_bigint(integer, source),
        _ => false,
    });

    if all_numeric {
        out.push_str(&format!("{export}enum {name} {{\n"));
        for (key, value, docs) in variants {
            if let Some(docs) = docs {
                push_jsdoc(out, &extract_documentation(docs, source), "  ");
            }
            out.push_str(&format!(
                "  {} = {},\n",
                typescript_property_name(key.text(source)),
                simple_type_to_ts(value, source)
            ));
        }
        out.push_str("}\n\n");
    } else {
        out.push_str(&format!("{export}type {name} =\n"));
        for (index, (key, value, docs)) in variants.iter().enumerate() {
            let payload_ts = simple_type_to_ts(value, source);
            if let Some(docs) = docs {
                push_jsdoc(out, &extract_documentation(docs, source), "  ");
            }
            let suffix = if index + 1 == variants.len() { ";" } else { "" };
            out.push_str(&format!(
                "  | {{ kind: \"{}\"; value: {payload_ts} }}{suffix}\n",
                key.text(source)
            ));
        }
        out.push('\n');
    }
}

// ── AST → TypeScript string ─────────────────────────────────────────

fn type_to_ts(ty: &Type, source: &str) -> String {
    match ty {
        Type::Simple(simple) => optional_aware_ts(simple, source),
        Type::Tuple(items) => format!(
            "[{}]",
            items
                .iter()
                .map(|value| optional_aware_ts(value, source))
                .collect::<Vec<_>>()
                .join(", ")
        ),
        Type::Set(set) => match (&set.element_type, &set.values) {
            (_, Some(values)) if values.is_empty() => "never".to_string(),
            (_, Some(values)) => values
                .iter()
                .map(|value| literal_to_ts(value, source))
                .collect::<Vec<_>>()
                .join(" | "),
            (Some(element), None) => format!("Set<{}>", simple_type_to_ts(element, source)),
            (None, None) => unreachable!("the parser rejects sets without a type or prefill"),
        },
        Type::Struct(fields) => format!(
            "{{ {} }}",
            fields
                .iter()
                .map(|(key, value, docs)| format!(
                    "{}{}: {}",
                    inline_jsdoc(docs.as_ref(), source),
                    typescript_property_name(key.text(source)),
                    simple_type_to_ts(value, source)
                ))
                .collect::<Vec<_>>()
                .join("; ")
        ),
        Type::Enum(variants) => variants
            .iter()
            .map(|(key, value, docs)| {
                format!(
                    "{}{{ kind: \"{}\"; value: {} }}",
                    inline_jsdoc(docs.as_ref(), source),
                    key.text(source),
                    simple_type_to_ts(value, source)
                )
            })
            .collect::<Vec<_>>()
            .join(" | "),
        Type::Sum(items) => items
            .iter()
            .map(|value| optional_aware_ts(value, source))
            .collect::<Vec<_>>()
            .join(" | "),
        Type::Intersection(items) => items
            .iter()
            .map(|value| simple_type_to_ts(value, source))
            .collect::<Vec<_>>()
            .join(" & "),
    }
}

/// Struct fields spell optionality with `?:`. Aliases, tuples, and unions have
/// no such marker, so it has to become an explicit `| undefined`.
fn optional_aware_ts(ty: &SimpleType, source: &str) -> String {
    match ty.is_optional() {
        true => format!("{} | undefined", simple_type_to_ts(ty, source)),
        false => simple_type_to_ts(ty, source),
    }
}

fn simple_type_to_ts(ty: &SimpleType, source: &str) -> String {
    match ty.inner() {
        SimpleType::Literal(literal) => literal_to_ts(literal, source),
        SimpleType::Identifier(identifier, arguments) => {
            named_type_to_ts(identifier.text(source), arguments.as_deref(), source)
        }
        SimpleType::Array(identifier, arguments) => {
            format!(
                "{}[]",
                named_type_to_ts(identifier.text(source), arguments.as_deref(), source)
            )
        }
        SimpleType::Optional(_) => unreachable!("inner() unwraps every optional layer"),
    }
}

fn named_type_to_ts(name: &str, arguments: Option<&[SimpleType]>, source: &str) -> String {
    if let ("Dict", Some([key, value])) = (name, arguments) {
        return format!(
            "Record<{}, {}>",
            simple_type_to_ts(key, source),
            simple_type_to_ts(value, source)
        );
    }

    // Utilities are operations: TypeScript spells several of them differently.
    if let Some([target, ..]) = arguments {
        let target = simple_type_to_ts(target, source);
        match name {
            "Keyof" => return format!("keyof {target}"),
            "Required" => return format!("NonNullable<{target}>"),
            "Complete" => return format!("Required<{target}>"),
            _ => {}
        }
    }

    let base = native_type_to_ts(name).unwrap_or(name);
    match arguments {
        None => base.to_string(),
        Some(arguments) => format!(
            "{base}<{}>",
            arguments
                .iter()
                .map(|value| simple_type_to_ts(value, source))
                .collect::<Vec<_>>()
                .join(", ")
        ),
    }
}

// ── Helpers ─────────────────────────────────────────────────────────

fn format_generic_params(
    generics: Option<&[(TokenData, Option<TokenData>)]>,
    source: &str,
) -> String {
    let Some(generics) = generics.filter(|generics| !generics.is_empty()) else {
        return String::new();
    };

    format!(
        "<{}>",
        generics
            .iter()
            .map(|(name, constraint)| {
                match constraint.map(|constraint| constraint.text(source)) {
                    Some("KeyTrait") => {
                        format!(
                            "{} extends string | number | bigint | symbol",
                            name.text(source)
                        )
                    }
                    _ => name.text(source).to_string(),
                }
            })
            .collect::<Vec<_>>()
            .join(", ")
    )
}

fn native_type_to_ts(name: &str) -> Option<&'static str> {
    Some(match name {
        "string" | "char" | "uuid" | "email" | "url" | "hostname" | "ip" | "ipv4" | "ipv6"
        | "semver" | "strong_password" | "date" | "datetime" | "duration" | "xml" | "yaml"
        | "json" | "toml" | "csv" | "tsv" => "string",
        "bool" => "boolean",
        "number" | "i4" | "i8" | "i16" | "i32" | "u4" | "u8" | "u16" | "u32" | "f32" | "f64"
        | "decimal" => "number",
        "i64" | "i128" | "u64" | "u128" | "bigint" | "integer" => "bigint",
        "binary" => "Uint8Array",
        "regex" => "RegExp",
        "NEVER" => "never",
        "any" => "any",
        "null" => "null",
        "TS::symbol" => "symbol",
        _ => return None,
    })
}

fn has_native_typescript_mapping(name: &str) -> bool {
    name == "Dict" || native_type_to_ts(name).is_some()
}

fn literal_to_ts(lit: &Literal, source: &str) -> String {
    match lit {
        Literal::Int(integer) if integer_uses_bigint(integer, source) => {
            format!("{}n", integer.value)
        }
        Literal::Int(integer) => integer.value.to_string(),
        Literal::Float(float) => float.value.to_string(),
        Literal::String(s, _) => format!("\"{s}\""),
        Literal::Boolean(b, _) => b.to_string(),
    }
}

fn integer_uses_bigint(integer: &IntLiteral, source: &str) -> bool {
    if integer.cast.is_some_and(|cast| {
        matches!(
            cast.text(source),
            "i64" | "i128" | "u64" | "u128" | "bigint"
        )
    }) {
        return true;
    }

    integer
        .value
        .to_string()
        .parse::<i64>()
        .map_or(true, |value| {
            !(-9_007_199_254_740_991..=9_007_199_254_740_991).contains(&value)
        })
}

fn format_annotation(annotation: &Annotation, source: &str) -> String {
    if annotation.ident.text(source) == "deprecated" {
        return match annotation.params.first() {
            Some(Expr::Type(Type::Simple(SimpleType::Literal(Literal::String(reason, _))))) => {
                format!("@deprecated {}", reason.replace("*/", "* /"))
            }
            _ => "@deprecated".to_string(),
        };
    }
    if annotation.params.is_empty() {
        format!("@{}", annotation.ident.text(source))
    } else {
        let arg_strs: Vec<String> = annotation
            .params
            .iter()
            .map(|value| expr_to_ts(value, source))
            .collect();
        format!(
            "@{}({})",
            annotation.ident.text(source),
            arg_strs.join(", ")
        )
    }
}

fn expr_to_ts(expr: &Expr, source: &str) -> String {
    match expr {
        Expr::Regex(token) => token.text(source).to_string(),
        Expr::Annotation(annotation) => format_annotation(annotation, source),
        Expr::Type(ty) => type_to_ts(ty, source),
    }
}

fn is_optional(ty: &SimpleType) -> bool {
    ty.is_optional()
}

fn is_all_required_literals(types: &[SimpleType]) -> bool {
    types.iter().all(|ty| matches!(ty, SimpleType::Literal(_)))
}

fn push_jsdoc(out: &mut String, docs: &str, indent: &str) {
    out.push_str(&format_jsdoc(docs, indent));
}

fn format_jsdoc(docs: &str, indent: &str) -> String {
    let mut result = format!("{indent}/**\n");
    for line in docs.lines() {
        result.push_str(&format!("{indent} * {line}\n"));
    }
    result.push_str(&format!("{indent} */\n"));
    result
}

fn inline_jsdoc(docs: Option<&xenomorph_common::TokenData>, source: &str) -> String {
    docs.map(|docs| {
        format!(
            "/** {} */ ",
            extract_documentation(docs, source)
                .split_whitespace()
                .collect::<Vec<_>>()
                .join(" ")
        )
    })
    .unwrap_or_default()
}

fn ts_import_specifier(from_module_path: &str, to_module_path: &str) -> String {
    relative_module_path(from_module_path, to_module_path)
}

fn typescript_property_name(wire_name: &str) -> String {
    if is_typescript_identifier_name(wire_name) {
        wire_name.to_string()
    } else {
        typescript_string_literal(wire_name)
    }
}

fn is_typescript_identifier_name(candidate: &str) -> bool {
    let mut characters = candidate.chars();
    let Some(first) = characters.next() else {
        return false;
    };
    (first == '_' || first == '$' || first.is_alphabetic())
        && characters
            .all(|character| character == '_' || character == '$' || character.is_alphanumeric())
}

fn typescript_string_literal(value: &str) -> String {
    let mut output = String::from("\"");
    for character in value.chars() {
        match character {
            '\\' => output.push_str("\\\\"),
            '"' => output.push_str("\\\""),
            '\n' => output.push_str("\\n"),
            '\r' => output.push_str("\\r"),
            '\t' => output.push_str("\\t"),
            control if control.is_control() => {
                output.push_str(&format!("\\u{:04X}", control as u32));
            }
            character => output.push(character),
        }
    }
    output.push('"');
    output
}

